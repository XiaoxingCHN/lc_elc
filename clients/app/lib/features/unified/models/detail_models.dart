/// One line of an issue record: what left which bag, and how much came back.
class IssueLineRecord {
  const IssueLineRecord({
    required this.id,
    required this.bagId,
    required this.bagTrace,
    required this.itemKey,
    required this.itemName,
    required this.quantity,
    required this.returnedQuantity,
    required this.outstandingQuantity,
    required this.locationCode,
    this.raw = const <String, dynamic>{},
  });

  /// `issue_line_id` for `/lab/api/inventory/return`.
  final int? id;
  final int? bagId;
  final String bagTrace;
  final String itemKey;
  final String itemName;
  final double? quantity;
  final double? returnedQuantity;
  final double? outstandingQuantity;
  final String locationCode;
  final Map<String, dynamic> raw;

  bool get hasId => id != null && id! > 0;

  /// Unreturned quantity: server value first, else issued - returned.
  double get outstanding {
    if (outstandingQuantity != null) return outstandingQuantity!;
    final issued = quantity ?? 0;
    final returned = returnedQuantity ?? 0;
    final value = issued - returned;
    return value > 0 ? value : 0;
  }

  factory IssueLineRecord.fromJson(Map<String, dynamic> json) {
    return IssueLineRecord(
      // `issue_line_id` FIRST: the return endpoint needs that exact id, and a
      // flat issue payload may also carry a generic `id` for something else.
      id: firstInt(json, const ['issue_line_id', 'line_id', 'id']),
      bagId: firstInt(json, const ['bag_id']) ??
          firstInt(asMap(firstValue(json, const ['bag'])), const ['id']),
      bagTrace: firstString(
            json,
            const ['bag_trace', 'trace_code', 'bag_code', 'lot_name'],
          ) ??
          '',
      itemKey: deriveItemKey(json) ?? '',
      itemName: firstString(json, const ['item_name', 'product_name', 'name', 'item']) ?? '',
      quantity: firstDouble(json, const ['quantity', 'qty', 'issued_quantity']),
      returnedQuantity: firstDouble(
        json,
        const ['returned_quantity', 'returned', 'return_qty'],
      ),
      outstandingQuantity: firstDouble(
        json,
        const ['outstanding_quantity', 'outstanding', 'unreturned_quantity'],
      ),
      locationCode:
          firstString(json, const ['location_code', 'location_name', 'location']) ?? '',
      raw: json,
    );
  }
}

/// One issue (领料单) with its lines.
///
/// The workflow addon currently returns `/lab/api/inventory/issues` as a FLAT
/// list of line-level rows (`{issue_line_id, bag_id, outstanding_quantity,
/// borrower_id, ...}`). [IssuePage.fromJson] therefore accepts BOTH shapes: a
/// nested `{issue, lines: [...]}` record and flat rows, which are grouped by
/// `issue_id` when the server sends one.
class IssueRecord {
  const IssueRecord({
    required this.id,
    required this.project,
    required this.borrowerId,
    required this.borrowerName,
    required this.actorName,
    required this.itemKey,
    required this.itemName,
    required this.issuedAt,
    required this.outstandingQuantity,
    required this.note,
    required this.lines,
    this.raw = const <String, dynamic>{},
  });

  final int? id;
  final String project;
  final int? borrowerId;
  final String borrowerName;
  final String actorName;
  final String itemKey;
  final String itemName;
  final DateTime? issuedAt;
  final double? outstandingQuantity;
  final String note;
  final List<IssueLineRecord> lines;
  final Map<String, dynamic> raw;

  bool get hasId => id != null && id! > 0;

  double get outstanding {
    if (outstandingQuantity != null) return outstandingQuantity!;
    return lines.fold<double>(0, (sum, line) => sum + line.outstanding);
  }

  String get displayTitle {
    if (project.isNotEmpty) return project;
    if (itemName.isNotEmpty) return itemName;
    if (id != null) return '领料单 #$id';
    return '领料单';
  }

  /// Adds one line (used while grouping a flat issue payload).
  IssueRecord withLine(IssueLineRecord line) {
    return IssueRecord(
      id: id,
      project: project,
      borrowerId: borrowerId,
      borrowerName: borrowerName,
      actorName: actorName,
      itemKey: itemKey.isNotEmpty ? itemKey : line.itemKey,
      itemName: itemName.isNotEmpty ? itemName : line.itemName,
      issuedAt: issuedAt,
      outstandingQuantity: null,
      note: note,
      lines: <IssueLineRecord>[...lines, line],
      raw: raw,
    );
  }

  /// Builds a record from ONE flat line-level row.
  factory IssueRecord.fromFlatLine(
    Map<String, dynamic> json,
    IssueLineRecord line,
  ) {
    final borrowerRef = asReference(firstValue(json, const ['borrower', 'borrower_id']));
    return IssueRecord(
      // The grouping id when present; otherwise the line id (still a unique,
      // selectable record - the UI never invents an issue).
      id: firstInt(json, const ['issue_id', 'issue_record_id']) ?? line.id,
      project: firstString(json, const ['project', 'project_name', 'purpose']) ?? '',
      borrowerId: firstInt(json, const ['borrower_id']) ?? borrowerRef.id,
      borrowerName: firstString(json, const ['borrower_name', 'borrower']) ??
          borrowerRef.name ??
          '',
      actorName: firstString(json, const ['actor_name', 'operator_name', 'actor']) ?? '',
      itemKey: line.itemKey,
      itemName: line.itemName,
      issuedAt: asDateTime(
        firstValue(json, const ['issued_at', 'create_date', 'at', 'date']),
      ),
      outstandingQuantity:
          firstDouble(json, const ['outstanding_quantity', 'outstanding']),
      note: firstString(json, const ['note', 'remark', 'memo']) ?? '',
      lines: <IssueLineRecord>[line],
      raw: json,
    );
  }

  factory IssueRecord.fromJson(Map<String, dynamic> json) {
    final borrowerRef = asReference(firstValue(json, const ['borrower', 'borrower_id']));
    final lines = asMapList(json['lines'] ?? json['line_ids']);
    return IssueRecord(
      id: firstInt(json, const ['issue_id', 'id']),
      project: firstString(json, const ['project', 'project_name', 'purpose']) ?? '',
      borrowerId: firstInt(json, const ['borrower_id']) ?? borrowerRef.id,
      borrowerName: firstString(json, const ['borrower_name']) ??
          borrowerRef.name ??
          asReference(firstValue(json, const ['borrower'])).name ??
          '',
      actorName: (() {
        final reference = asReference(
          firstValue(json, const ['actor', 'operator', 'create_uid', 'user_id']),
        );
        return reference.name ??
            firstString(json, const ['actor_name', 'operator_name']) ??
            '';
      })(),
      itemKey: deriveItemKey(json) ?? '',
      itemName: (() {
        final direct = firstString(json, const ['item_name', 'product_name', 'name']);
        if (direct != null) return direct;
        for (final line in lines) {
          final name = firstString(line, const ['item_name', 'product_name', 'name']);
          if (name != null) return name;
        }
        return '';
      })(),
      issuedAt: asDateTime(
        firstValue(json, const ['issued_at', 'create_date', 'at', 'date']),
      ),
      outstandingQuantity: firstDouble(
        json,
        const ['outstanding_quantity', 'outstanding', 'unreturned_quantity'],
      ),
      note: firstString(json, const ['note', 'remark', 'memo']) ?? '',
      lines: lines.map(IssueLineRecord.fromJson).toList(),
      raw: json,
    );
  }
}

/// One page of `/lab/api/inventory/issues`.
class IssuePage {
  const IssuePage({required this.issues, required this.nextCursor});

  final List<IssueRecord> issues;
  final String? nextCursor;

  bool get hasMore => nextCursor != null && nextCursor!.isNotEmpty;

  factory IssuePage.fromJson(Map<String, dynamic> json) {
    final records = <IssueRecord>[];
    final indexByIssueId = <int, int>{};

    for (final entry in asMapList(json['issues'])) {
      final nested = asMapList(entry['lines'] ?? entry['line_ids']);
      if (nested.isNotEmpty) {
        final record = IssueRecord.fromJson(entry);
        records.add(record);
        if (record.id != null) indexByIssueId[record.id!] = records.length - 1;
        continue;
      }

      // Flat line-level row: group by issue id when the server sends one.
      final line = IssueLineRecord.fromJson(entry);
      final issueId = firstInt(entry, const ['issue_id', 'issue_record_id']);
      final known = issueId == null ? null : indexByIssueId[issueId];
      if (known != null) {
        records[known] = records[known].withLine(line);
        continue;
      }
      final record = IssueRecord.fromFlatLine(entry, line);
      records.add(record);
      if (issueId != null) indexByIssueId[issueId] = records.length - 1;
    }

    return IssuePage(
      issues: records,
      nextCursor: asString(json['next_cursor']),
    );
  }

  static const IssuePage empty = IssuePage(issues: <IssueRecord>[], nextCursor: null);
}

/// `/lab/api/catalog/detail` response.
class CatalogDetail {
  const CatalogDetail({
    required this.item,
    required this.locations,
    required this.bags,
    required this.files,
    required this.history,
    this.materials = const <LabMaterial>[],
    this.raw = const <String, dynamic>{},
  });

  /// The card itself, when the server echoes it.
  final UnifiedItem? item;

  /// Every LOCAL archive behind this card (each with its own SN). Empty when the
  /// server did not send the list; the receipt flow then requires the server's
  /// own AMBIGUOUS_MATERIAL answer instead of guessing.
  final List<LabMaterial> materials;

  /// Per-location breakdown of the internal stock.
  final List<LabStockLocation> locations;

  /// The physical bags/batches behind this card (each with its own trace code).
  final List<LabBag> bags;

  /// Captured files (datasheets, manuals).
  final List<LabFile> files;

  /// Recent operations for this item.
  final List<LabOperation> history;

  final Map<String, dynamic> raw;

  /// Sum of the per-location quantities, or `null` when the server sent none.
  double? get locationTotal {
    if (locations.isEmpty) return null;
    if (locations.every((location) => location.quantity == null)) return null;
    return locations.fold<double>(
      0,
      (sum, location) => sum + (location.quantity ?? 0),
    );
  }

  /// Sum of the bag quantities, or `null` when the server sent none.
  double? get bagTotal {
    if (bags.isEmpty) return null;
    if (bags.every((bag) => bag.quantity == null)) return null;
    return bags.fold<double>(0, (sum, bag) => sum + (bag.quantity ?? 0));
  }

  static const CatalogDetail empty = CatalogDetail(
    item: null,
    locations: <LabStockLocation>[],
    bags: <LabBag>[],
    files: <LabFile>[],
    history: <LabOperation>[],
    materials: <LabMaterial>[],
  );

  /// Distinct template ids of the archives behind this card.
  List<int> get templateIds {
    final ids = <int>[];
    for (final material in materials) {
      if (material.hasTemplateId && !ids.contains(material.templateId)) {
        ids.add(material.templateId!);
      }
    }
    if (ids.isEmpty && item != null) return item!.labTemplateIds;
    return ids;
  }

  /// True when this card has several archives, so a receipt MUST ask which one.
  bool get hasMultipleArchives => templateIds.length > 1;

  factory CatalogDetail.fromJson(Map<String, dynamic> json) {
    final itemJson = asMap(json['item']);
    return CatalogDetail(
      item: itemJson.isEmpty ? null : UnifiedItem.fromJson(itemJson),
      materials: LabMaterial.listFrom(
        json['materials'] ??
            json['lab_materials'] ??
            json['locals'] ??
            json['archives'] ??
            json['templates'],
      ),
      locations: asMapList(json['locations'] ?? json['location_ids'])
          .map(LabStockLocation.fromJson)
          .toList(),
      bags: asMapList(json['bags'] ?? json['bag_ids']).map(LabBag.fromJson).toList(),
      files: LabFile.listFrom(json['files'] ?? json['attachments']),
      history: asMapList(json['history'] ?? json['operations'])
          .map(LabOperation.fromJson)
          .toList(),
      raw: json,
    );
  }
