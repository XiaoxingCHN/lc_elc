/// One LOCAL material archive behind a card: `product.template` + its SN.
///
/// A card identified by one C code may aggregate several archives (root's rule:
/// one code = ONE card, but every SN stays a separate business record). Choosing
/// a receipt target must therefore be explicit: the operator picks THIS archive,
/// and the server validates it (accessible / same company / matches the canonical
/// C code). Nothing in this client may substitute "the first one".
class LabMaterial {
  const LabMaterial({
    required this.templateId,
    required this.productId,
    required this.sn,
    required this.name,
    required this.quantity,
    required this.available,
    this.raw = const <String, dynamic>{},
  });

  /// `product.template` id - the value sent as `receipt.product_template_id`.
  final int? templateId;

  /// `product.product` id, when the server reports it.
  final int? productId;

  /// The material's own SN. Never generated by the client.
  final String sn;

  final String name;
  final double? quantity;
  final double? available;
  final Map<String, dynamic> raw;

  bool get hasTemplateId => templateId != null && templateId! > 0;

  /// What the picker shows: the SN when there is one, otherwise the archive id.
  String get display {
    final parts = <String>[
      if (sn.isNotEmpty) sn,
      if (name.isNotEmpty && name != sn) name,
      if (sn.isEmpty && name.isEmpty && templateId != null) '档案 #$templateId',
    ];
    return parts.isEmpty ? '本地档案' : parts.join(' · ');
  }

  factory LabMaterial.fromJson(Map<String, dynamic> json) {
    return LabMaterial(
      templateId: firstInt(
        json,
        const ['product_template_id', 'template_id', 'lab_template_id', 'id'],
      ),
      productId: firstInt(json, const ['product_id', 'lab_product_id']),
      sn: firstString(json, const ['sn', 'sn_code', 'lab_sn', 'lot_name']) ?? '',
      name: firstString(json, const ['name', 'display_name', 'product_name']) ?? '',
      quantity: firstDouble(json, const ['quantity', 'lab_quantity', 'qty_available']),
      available: firstDouble(
        json,
        const ['available_quantity', 'lab_available_quantity', 'free_quantity'],
      ),
      raw: json,
    );
  }

  /// Reads a candidates / materials list from any of the shapes the server uses.
  static List<LabMaterial> listFrom(Object? value) {
    return asMapList(value)
        .map(LabMaterial.fromJson)
        .where((material) => material.hasTemplateId || material.sn.isNotEmpty)
        .toList();
  }
}

/// One physical storage location (`stock.location`), with its lab库码.
///
/// A location always has its OWN code and its OWN label payload
/// (`LABL:<code>`) - it is never identified by a material code.
class LabStockLocation {
  const LabStockLocation({
    required this.id,
    required this.code,
    required this.name,
    required this.path,
    this.quantity,
    this.raw = const <String, dynamic>{},
  });

  final int? id;

  /// The printed 库码, e.g. `K000001`.
  final String code;
  final String name;

  /// Full Odoo path, e.g. `Lab/R01`.
  final String path;

  /// Quantity held here, when the server reports it for one item.
  final double? quantity;

  final Map<String, dynamic> raw;

  bool get hasId => id != null && id! > 0;

  /// `K000001 · R01`, or whatever exists.
  String get display {
    final parts = <String>[
      if (code.isNotEmpty) code,
      if (name.isNotEmpty && name != code) name,
    ];
    if (parts.isEmpty) return path.isEmpty ? '未命名库位' : path;
    return parts.join(' · ');
  }

  /// Label payload this location prints (`LABL:K000001`).
  String get labelPayload => locationPayload(code);

  factory LabStockLocation.fromJson(Map<String, dynamic> json) {
    return LabStockLocation(
      id: firstInt(json, const ['id', 'location_id']),
      code: firstString(json, const ['code', 'location_code', 'barcode', 'name']) ?? '',
      name: firstString(json, const ['name', 'display_name', 'location_name']) ?? '',
      path: firstString(json, const ['path', 'complete_name', 'location_path']) ?? '',
      quantity: firstDouble(json, const ['quantity', 'qty', 'on_hand', 'available']),
      raw: json,
    );
  }
}

/// One physical bag / batch: the unit a 追溯码 identifies.
///
/// `trace_code` is the value printed as `LABB:<trace_code>` on the bag label.
class LabBag {
  const LabBag({
    required this.id,
    required this.traceCode,
    required this.sn,
    required this.itemKey,
    required this.itemName,
    this.productTemplateId,
    required this.locationId,
    required this.locationCode,
    required this.locationName,
    required this.quantity,
    required this.supplier,
    required this.note,
    required this.createdAt,
    this.raw = const <String, dynamic>{},
  });

  final int? id;
  final String traceCode;
  final String sn;
  final String itemKey;
  final String itemName;

  /// The local archive this bag was created from, when the server reports it.
  /// A bag scan uses it to keep the EXACT template instead of guessing.
  final int? productTemplateId;

  final int? locationId;
  final String locationCode;
  final String locationName;
  final double? quantity;
  final String supplier;
  final String note;
  final DateTime? createdAt;
  final Map<String, dynamic> raw;

  bool get hasId => id != null && id! > 0;

  /// Bag label payload (`LABB:TRACE000001`).
  String get labelPayload => bagPayload(traceCode);

  String get display {
    if (traceCode.isNotEmpty) return traceCode;
    if (id != null) return '袋 #$id';
    return '未命名袋';
  }

  double get remaining => quantity ?? 0;

  factory LabBag.fromJson(Map<String, dynamic> json) {
    final locationJson = asMap(firstValue(json, const ['location', 'location_id']));
    return LabBag(
      id: firstInt(json, const ['id', 'bag_id']),
      traceCode: firstString(
            json,
            const ['trace_code', 'tracecode', 'bag_code', 'barcode', 'code', 'name'],
          ) ??
          '',
      sn: firstString(json, const ['sn', 'sn_code', 'lab_sn', 'lot_name']) ?? '',
      itemKey: deriveItemKey(json) ?? '',
      itemName: firstString(json, const ['item_name', 'product_name', 'name']) ?? '',
      productTemplateId: firstInt(
        json,
        const ['product_template_id', 'template_id', 'lab_template_id'],
      ),
      locationId: firstInt(json, const ['location_id']) ??
          firstInt(locationJson, const ['id']),
      locationCode: firstString(json, const ['location_code']) ??
          firstString(locationJson, const ['code', 'location_code', 'name']) ??
          '',
      locationName: firstString(json, const ['location_name']) ??
          firstString(locationJson, const ['name', 'display_name']) ??
          '',
      quantity: firstDouble(
        json,
        const ['quantity', 'qty', 'remaining_quantity', 'on_hand'],
      ),
      supplier: firstString(
            json,
            const ['supplier', 'supplier_name', 'supplier_metadata', 'source'],
          ) ??
          '',
      note: firstString(json, const ['note', 'remark', 'memo']) ?? '',
      createdAt: asDateTime(
        firstValue(json, const ['created_at', 'create_date', 'receipt_date', 'at']),
      ),
      raw: json,
    );
  }
}

/// One captured file (datasheet / manual) of a catalog item.
class LabFile {
  const LabFile({
    required this.name,
    required this.url,
    required this.type,
    this.size,
    this.raw = const <String, dynamic>{},
  });

  final String name;

  /// Real, server-supplied URL. Never constructed by this client.
  final String url;

  /// e.g. `pdf_property`, `pdf`, `datasheet`.
  final String type;
  final int? size;
  final Map<String, dynamic> raw;

  bool get isManual =>
      isPdf || type.toLowerCase().contains('pdf') || type.toLowerCase().contains('manual');

  bool get isPdf {
    final lower = url.toLowerCase();
    final nameLower = name.toLowerCase();
    return type.toLowerCase().contains('pdf') ||
        lower.endsWith('.pdf') ||
        lower.contains('.pdf?') ||
        nameLower.endsWith('.pdf');
  }

  String get displayName {
    if (name.isNotEmpty) return name;
    final uri = Uri.tryParse(url);
    final last = uri?.pathSegments.isNotEmpty == true ? uri!.pathSegments.last : '';
    if (last.isNotEmpty) return last;
    return '资料文件';
  }

  /// Flattens the two shapes the capture uses:
  /// `{fileType, detailVOList:[{fileName,fileUrl}]}` and
  /// `{fileType, fileName, fileUrl}`.
  static List<LabFile> listFrom(Object? value) {
    final result = <LabFile>[];
    for (final entry in asMapList(value)) {
      final type = firstString(entry, const ['fileType', 'file_type', 'type']) ?? '';
      final nested = asMapList(entry['detailVOList'] ?? entry['files'] ?? entry['items']);
      final directUrl = asAssetReference(firstValue(entry, const ['fileUrl', 'file_url', 'url']));
      if (directUrl != null) {
        result.add(
          LabFile(
            name: firstString(entry, const ['fileName', 'file_name', 'name']) ?? '',
            url: directUrl,
            type: type,
            size: firstInt(entry, const ['fileSize', 'size']),
            raw: entry,
          ),
        );
      }
      for (final file in nested) {
        final url = asAssetReference(firstValue(file, const ['fileUrl', 'file_url', 'url']));
        if (url == null) continue;
        result.add(
          LabFile(
            name: firstString(file, const ['fileName', 'file_name', 'name']) ?? '',
            url: url,
            type: firstString(file, const ['fileType', 'file_type', 'type']) ?? type,
            size: firstInt(file, const ['fileSize', 'size']),
            raw: file,
          ),
        );
      }
    }
    // De-duplicate identical URLs so the manual list cannot show a file twice.
    final seen = <String>{};
    return result.where((file) => seen.add(file.url)).toList();
  }
}

/// One immutable stock operation from the history / trace feed.
///
/// The workflow addon owns the exact key names; this reader accepts the aliases
/// it is most likely to use and ALWAYS keeps [raw], so an unmapped field is
/// still visible (never silently dropped). The UI prints the mapped fields and
/// shows `raw` on demand.
class LabOperation {
  const LabOperation({
    required this.id,
    required this.kind,
    required this.itemKey,
    required this.itemName,
    required this.quantity,
    required this.outstandingQuantity,
    required this.actor,
    required this.borrower,
    required this.project,
    required this.bagTrace,
    required this.locationCode,
    required this.at,
    required this.note,
    this.raw = const <String, dynamic>{},
  });

  final int? id;

  /// `receipt` / `issue` / `return` (or the server's own spelling).
  final String kind;
  final String itemKey;
  final String itemName;
  final double? quantity;

  /// Remaining unreturned quantity, when this row is an issue.
  final double? outstandingQuantity;

  /// The authenticated operator who actually performed the operation.
  final String actor;

  /// The person the material was issued to (a system account, never free text).
  final String borrower;

  final String project;
  final String bagTrace;
  final String locationCode;
  final DateTime? at;
  final String note;
  final Map<String, dynamic> raw;

  bool get isReceipt => _kindContains('receipt') || _kindContains('in') || _kindContains('入库');
  bool get isIssue => _kindContains('issue') || _kindContains('out') || _kindContains('领');
  bool get isReturn => _kindContains('return') || _kindContains('归还');

  bool _kindContains(String needle) => kind.toLowerCase().contains(needle);

  /// Chinese title for the history timeline.
  String get title {
    if (isReceipt) return '入库';
    if (isReturn) return '归还';
    if (isIssue) return '领料';
    return kind.isEmpty ? '库存操作' : kind;
  }

  String get signedQuantity {
    if (quantity == null) return '';
    final text = UnifiedItem.formatQuantity(quantity!);
    if (isReceipt || isReturn) return '+$text';
    if (isIssue) return '-$text';
    return text;
  }

  factory LabOperation.fromJson(Map<String, dynamic> json) {
    String? person(List<String> keys) {
      for (final key in keys) {
        final value = json[key];
        if (value == null || value == false) continue;
        final reference = asReference(value);
        if (reference.name != null && reference.name!.isNotEmpty) {
          return reference.name;
        }
        final text = asString(value);
        if (text != null) return text;
      }
      return null;
    }

    return LabOperation(
      id: firstInt(json, const ['id', 'operation_id', 'move_id']),
      kind: firstString(
            json,
            const ['kind', 'type', 'operation_type', 'op_type', 'move_type', 'state'],
          ) ??
          '',
      itemKey: deriveItemKey(json) ?? '',
      itemName: firstString(
            json,
            const ['item_name', 'product_name', 'material_name', 'name', 'item'],
          ) ??
          '',
      quantity: firstDouble(
        json,
        const ['quantity', 'qty', 'amount', 'done_quantity'],
      ),
      outstandingQuantity: firstDouble(
        json,
        const ['outstanding_quantity', 'outstanding', 'unreturned_quantity'],
      ),
      actor: person(const [
        'actor',
        'actor_name',
        'operator',
        'operator_name',
        'done_by',
        'create_uid',
        'user_id',
      ]) ??
          '',
      borrower: person(const [
        'borrower',
        'borrower_name',
        'borrower_id',
        'issued_to',
        'partner_id',
      ]) ??
          '',
      project: firstString(json, const ['project', 'project_name', 'purpose']) ?? '',
      bagTrace: firstString(
            json,
            const ['bag_trace', 'trace_code', 'bag_code', 'bag', 'lot_name'],
          ) ??
          '',
      locationCode: firstString(
            json,
            const ['location_code', 'location', 'location_name', 'dest_location'],
          ) ??
          '',
      at: asDateTime(
        firstValue(
          json,
          const ['at', 'timestamp', 'date', 'create_date', 'done_at', 'operation_date'],
        ),
      ),
      note: firstString(json, const ['note', 'remark', 'memo', 'description']) ?? '',
      raw: json,
    );
  }
}

